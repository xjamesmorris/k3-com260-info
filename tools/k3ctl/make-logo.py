"""Regenerate firmware/k3ctl/riscv_logo.h from the official RISC-V logo.

Downloads RISC-V International's published "secondary" (stacked) logo pack,
verifies its SHA-256, takes the single-colour white PNG unchanged in shape,
scales it to fit the 72x40 OLED and thresholds it to 1 bit (XBM, LSB-first,
as u8g2's drawXBMP expects). The logo is a RISC-V International trademark;
see README.md "Display" for the usage terms this relies on.

Requires Pillow. Run from tools/k3ctl:  python3 make-logo.py [--zip FILE]
"""
from __future__ import annotations

import argparse
import hashlib
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

URL = ("https://riscv.org/wp-content/uploads/2024/12/"
       "Secondary-Logo_RISC-V-Stacked-20230728T144248Z-001.zip")
SHA256 = "5bae02d0a27dfb4a6360e5518d5fbb84b6f4138d9405177c9ce8bebc956dab03"
MEMBER = "Secondary Logo_RISC-V Stacked/RISC-V_ Stacked_White.png"
MAX_W, MAX_H = 72, 40
THRESHOLD = 128
OUT = Path(__file__).resolve().parent / "firmware" / "k3ctl" / "riscv_logo.h"


def main() -> int:
    from PIL import Image

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--zip", type=Path, help="use an already-downloaded logo pack")
    args = ap.parse_args()

    data = args.zip.read_bytes() if args.zip else urllib.request.urlopen(URL, timeout=60).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        print(f"make-logo: SHA-256 mismatch: got {digest}, want {SHA256}", file=sys.stderr)
        return 1
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        im = Image.open(io.BytesIO(z.read(MEMBER))).convert("RGBA")

    alpha = im.getchannel("A")
    alpha = alpha.crop(alpha.getbbox())
    scale = min(MAX_W / alpha.width, MAX_H / alpha.height)
    w, h = round(alpha.width * scale), round(alpha.height * scale)
    bits = alpha.resize((w, h), Image.LANCZOS).point(lambda v: 1 if v >= THRESHOLD else 0)

    stride = (w + 7) // 8
    out = []
    for y in range(h):
        for bx in range(stride):
            byte = 0
            for i in range(8):
                x = bx * 8 + i
                if x < w and bits.getpixel((x, y)):
                    byte |= 1 << i
            out.append(byte)

    rows = [", ".join(f"0x{b:02x}" for b in out[i:i + 12]) for i in range(0, len(out), 12)]
    OUT.write_text(
        "// SPDX-License-Identifier: GPL-2.0-only\n"
        "// Generated by tools/k3ctl/make-logo.py; do not edit by hand.\n"
        "// RISC-V logo (stacked, white): a trademark of RISC-V International,\n"
        "// used under its brand guidelines for non-commercial projects. This\n"
        "// file's license grants no trademark rights.\n"
        f"// Source: {URL}\n"
        f"// Source SHA-256: {SHA256}, member: {MEMBER}\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"static const uint8_t RISCV_LOGO_W = {w};\n"
        f"static const uint8_t RISCV_LOGO_H = {h};\n"
        "static const unsigned char riscv_logo_bits[] PROGMEM = {\n  "
        + ",\n  ".join(rows) + "\n};\n")
    print(f"make-logo: wrote {OUT} ({w}x{h})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
